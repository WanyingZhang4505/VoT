PROTOCOL = "hic_codex_direct_scope16_paired_validation_v3_full_hic_one_memory_isolated"
PARAMETERS = {"memory_count": 1, "text_top_k": 5, "strict_history_start": True}
TEST6_HORIZON_MIGRATION = {
    ("SocialGood", 10): (6, 8),
    ("SocialGood", 12): (6, 8),
    ("Energy", 36): (12, 24),
    ("Energy", 48): (12, 24),
}


def _test6_query_memory_policy(
    contract, *, dataset, horizon, prior_online_case_ids=None,
):
    """Select the configured migration policy and preserve online order."""
    policy = {}
    migration_sources = TEST6_HORIZON_MIGRATION.get((dataset, horizon))
    online_round_id = contract.get("test6_round_id")
    if migration_sources is not None:
        policy["horizon_migration_protocol"] = "agent_test6_cross_horizon_v1"
        policy["allowed_source_horizons"] = list(migration_sources)
    elif (isinstance(online_round_id, str) and online_round_id.strip()
          and prior_online_case_ids is not None):
        policy["horizon_migration_protocol"] = TEST6_SEMANTIC_TRANSFER_PROTOCOL
        if not isinstance(prior_online_case_ids, list) or any(
            not isinstance(case_id, str) for case_id in prior_online_case_ids
        ):
            raise ValueError("Test 6 online transfer requires the completed prior-case list")
        policy["test6_prior_memory_case_ids"] = prior_online_case_ids
    elif isinstance(online_round_id, str) and online_round_id.strip():
        policy["horizon_migration_protocol"] = "agent_test6_sequential_online_v1"
        policy["allowed_source_horizons"] = [horizon]
    if isinstance(online_round_id, str) and online_round_id.strip():
        policy["test6_online_round_id"] = online_round_id
    return policy


def evaluation_memory_provenance_caveat(*, historical_backend, historical_memory_count,
                                        memory_source):
    """Describe only a verified Codex-generated frozen fit-memory bank."""
    if historical_backend != "codex_task_agent":
        raise ValueError("historical memory backend is not verified as Codex task agent")
    if type(historical_memory_count) is not int or historical_memory_count <= 0:
        raise ValueError("historical memory count must be a positive integer")
    if not isinstance(memory_source, str) or not memory_source.strip():
        raise ValueError("memory_source must be non-empty text")
    return (
        f"Development evaluation using {historical_memory_count} frozen fit memories "
        f"from {memory_source}; the historical LLM reflections were generated by "
        "Codex task agents. Validation summaries and forecasts were also generated "
        "by Codex task agents."
    )


def _invoke_prompt_identity(cache, call_id, prompt, *, call_json, validator):
    """Reuse an unchanged request; give changed prompt content a new task ID."""
    try:
        return cache.invoke(
            call_id, prompt, call_json=call_json, validator=validator,
        ), call_id
    except ValueError as error:
        if str(error) != "Codex task request identity changed for an existing call_id":
            raise
    prompt_digest = hashlib.sha256(prompt.encode("utf-8")).hexdigest()
    revised_call_id = f"{call_id}:prompt_{prompt_digest}"
    return cache.invoke(
        revised_call_id, prompt, call_json=call_json, validator=validator,
    ), revised_call_id


def canonical_hash(value):
    encoded = json.dumps(value, ensure_ascii=False, sort_keys=True,
                         separators=(",", ":"), allow_nan=False).encode("utf-8")
    return hashlib.sha256(encoded).hexdigest()


def _no_provider_call(*args, **kwargs):
    raise AssertionError("Agent validation must not call the DeepSeek API")


def _summary_response(response):
    if not isinstance(response, dict) or not response:
        raise ValueError("summary must be a non-empty JSON object")
    if "error" in response:
        return False
    if not all(isinstance(response.get(key), dict)
               for key in ("dataset_info", "predictive_factors", "forecast_outlook")):
        return False

    def strings(value):
        if isinstance(value, dict):
            return [text for item in value.values() for text in strings(item)]
        if isinstance(value, list):
            return [text for item in value for text in strings(item)]
        return [value] if isinstance(value, str) else []

    refusal_markers = ("isolation unavailable", "isolation could not be guaranteed",
                       "could not guarantee this task", "analysis was not performed",
                       "no analysis provided")
    if any(marker in text.casefold() for text in strings(response)
           for marker in refusal_markers):
        return False
    return True


def _rank_eligible_candidates(candidates, query):
    """Filter mixed-schema memories with identical task and temporal rules."""
    supported_versions = {
        CORRECTION_SCHEMA_VERSION,
        CORRECTION_SCHEMA_VERSION_V3,
        CORRECTION_SCHEMA_VERSION_V4,
        CORRECTION_SCHEMA_VERSION_TEST6_OUTCOME_BLIND,
    }
    grouped = {}
    excluded_counts = Counter()
    for candidate in candidates:
        metadata = candidate.get("metadata") if isinstance(candidate, dict) else None
        if not isinstance(metadata, dict):
            excluded_counts["invalid_record"] += 1
            continue
        version = metadata.get("correction_schema_version")
        if version not in supported_versions:
            excluded_counts["unsupported_correction_schema"] += 1
            continue
        prompt_version = metadata.get("correction_prompt_version")
        if version in {CORRECTION_SCHEMA_VERSION_V3, CORRECTION_SCHEMA_VERSION_V4}:
            if not isinstance(prompt_version, str) or not prompt_version.strip():
                excluded_counts["correction_prompt_version_missing"] += 1
                continue
        grouped.setdefault((version, prompt_version), []).append(candidate)

    eligible = []
    for (version, prompt_version), group in sorted(
        grouped.items(), key=lambda item: (item[0][0], item[0][1] or "")
    ):
        group_query = {
            **query,
            "required_correction_schema_version": version,
        }
        if prompt_version is not None:
            group_query["required_correction_prompt_version"] = prompt_version
        ranked = rank_applicable_memories(
            group,
            group_query,
            require_horizon_text_consistency=True,
        )
        eligible.extend(ranked["eligible"])
        excluded_counts.update(ranked["excluded_counts"])
    eligible.sort(key=lambda row: (-row["score"], row["case_id"]))
    return {"eligible": eligible, "excluded_counts": dict(sorted(excluded_counts.items()))}


def advance_agent_case(case, state, *, contract, template, dataset_description,
                       cache, store, embed_summary, persist,
                       prior_online_case_ids=None, retrieval_mode="applicable",
                       exclude_point_ids=None):
    """Run paired No Retrieval and one-memory, fresh-forecast Full HIC stages."""
    if retrieval_mode not in {"applicable", "direct_nearest"}:
        raise ValueError("retrieval_mode must be applicable or direct_nearest")
    horizon = contract["horizon"]
    validate_validation_window({"case": case}, expected_horizon=horizon)
    history_start = case.get("history_start")
    if retrieval_mode == "applicable" and (
            not isinstance(history_start, str) or not history_start.strip()):
        raise ValueError("strict HIC retrieval requires a valid case.history_start")
    if retrieval_mode == "applicable":
        try:
            datetime.fromisoformat(history_start.replace("Z", "+00:00"))
        except ValueError:
            try:
                date.fromisoformat(history_start)
            except ValueError:
                raise ValueError("strict HIC retrieval requires an ISO case.history_start") from None
    identity = canonical_hash({"case": case, "contract": contract, "template": template,
                               "description": dataset_description, "parameters": PARAMETERS,
                               "protocol": PROTOCOL, "retrieval_mode": retrieval_mode})
    if state.get("input_sha256", identity) != identity:
        raise ValueError("case input identity changed since its saved checkpoint")
    state["input_sha256"] = identity
    if state.get("status") == "forecast_complete":
        return state
    for request_sha in state.get("requests", {}).values():
        cache.mark_persisted(request_sha)

    def invoke(stage, prompt, validator, field, normalize=lambda response: response):
        cached, task_id = _invoke_prompt_identity(
            cache, f"{cache.run_id}:{case['case_id']}:H{horizon}:{stage}", prompt,
            call_json=_no_provider_call, validator=validator,
        )
        state[field] = normalize(cached["response"])
        request_sha = cached["request_identity"]["sha256"]
        state.setdefault("requests", {})[stage] = request_sha
        state.setdefault("request_task_ids", {})[stage] = task_id
        persist()
        cache.mark_persisted(request_sha)

    if "summary" not in state:
        invoke("summary_direct_v2", hic.build_summary_prompt(
            template, case["series"], case.get("news", ""),
            dataset_description=dataset_description, covariates=case.get("covariates"),
            news_quality_detail=case.get("news_quality_detail"), canonical_json_inputs=True,
            target=contract["target"], unit=contract["unit"], frequency=contract["frequency"],
            horizon=horizon), _summary_response, "summary")
    temporal_context = {
        "history_period": {
            "start": case.get("history_start"), "end": case.get("history_end"),
        },
        "forecast_period": {
            "start": case.get("target_start"), "end": case.get("target_end"),
        },
    }
    for period_name, period in temporal_context.items():
        if any(not isinstance(value, str) or not value.strip() for value in period.values()):
            raise ValueError(f"Test 6 paired prompt requires complete {period_name} dates")
    paired_input = {
        "summary": state["summary"],
        "history": case["series"],
        "horizon": horizon,
        "frequency": contract["frequency"],
        "target": contract["target"],
        "unit": contract["unit"],
        "covariates": case.get("covariates"),
        "dataset_description": dataset_description,
        "temporal_context": temporal_context,
    }
    if "baseline" not in state:
        invoke("baseline_no_retrieval_paired_v1",
            build_paired_direct_forecast_prompt(**paired_input),
            lambda response: _validated_forecast(response, horizon), "baseline",
            lambda response: _validated_forecast(response, horizon))

    if "query_embedding" not in state:
        vector = [float(value) for value in embed_summary(state["summary"])]
        if len(vector) != 1024:
            raise ValueError("BGE-M3 query embedding must contain 1024 dimensions")
        # Non-finite values are also rejected by canonical serialization and Qdrant.
        canonical_hash(vector)
        state["query_embedding"] = vector
        persist()

    trace = state.get("retrieval_trace")
    if (retrieval_mode == "applicable" and isinstance(trace, dict)
            and trace.get("transfer_projection_version")
            != TEST6_TRANSFER_PROJECTION_VERSION):
        state.setdefault("retrieval_trace_revision_history", []).append({
            "previous_projection_version": trace.get("transfer_projection_version"),
            "previous_trace_sha256": hashlib.sha256(
                json.dumps(trace, sort_keys=True, ensure_ascii=False,
                           separators=(",", ":"), allow_nan=False).encode("utf-8")
            ).hexdigest(),
            "previous_selected_point_ids": [
                item.get("point_id") for item in trace.get("selected", [])
                if isinstance(item, dict)
            ],
            "superseded_pending_task_id": state.get("pending_task_id"),
            "reason": "Test 6 transfer projection version changed; regenerate candidate scope checks and any pending B identity.",
        })
        state.pop("retrieval_trace", None)
        persist()

    if retrieval_mode == "direct_nearest" and "retrieval_trace" not in state:
        count = store.count(exclude_point_ids=exclude_point_ids)
        memory = (store.search(state["query_embedding"], limit=1,
                               exclude_point_ids=exclude_point_ids) if count else None)
        selected = []
        if memory is not None:
            correction = memory.get("correction")
            if not isinstance(correction, str) or not correction.strip():
                raise ValueError("nearest Qdrant point has no correction text")
            metadata = memory.get("metadata") or {}
            # Test 7 revises the correction on the retrieved point in place.
            # Keep the Test 6 payload convention readable for legacy runs.
            active_revision = metadata.get("test7_correction_revision")
            revision_field = "test7_correction_revision_id"
            if active_revision is None:
                active_revision = metadata.get("test6_transfer_revision")
                revision_field = "test6_transfer_revision_id"
            if active_revision is not None:
                correction = json.dumps(
                    {"stored_correction": correction,
                     "active_revision": active_revision,
                     "active_revision_id": metadata.get(revision_field)},
                    ensure_ascii=False, sort_keys=True, separators=(",", ":"),
                    allow_nan=False,
                )
            source_horizon = metadata.get("source_horizon", metadata.get("horizon"))
            selected = [{
                "point_id": memory["point_id"],
                "case_id": memory["case_id"],
                "correction": correction,
                "source_horizon": source_horizon if type(source_horizon) is int else None,
                "similarity": memory.get("score"),
                "source_dataset": metadata.get("dataset"),
                "source_unit": metadata.get("unit"),
                "source_frequency": metadata.get("frequency"),
                "active_revision_id": metadata.get(revision_field),
            }]
        state["retrieval_trace"] = {
            "mode": "direct_nearest", "candidate_count": count,
            "excluded_point_ids": list(exclude_point_ids or []),
            "selected": selected,
        }
        persist()

    if "retrieval_trace" not in state:
        count = store.count()
        candidates = store.search_many(state["query_embedding"], limit=count) if count else []
        for candidate in candidates:
            metadata = candidate.get("metadata") or {}
            candidate["history_series"] = metadata.get("history_series")
            candidate["baseline_behavior_profile"] = metadata.get("baseline_behavior_profile")
        query = {"case_id": case["case_id"], "dataset": case["dataset"],
                 "entity": case.get("group"),
                 "source_sha256": contract["source_sha256"],
                 "target": case.get("target") or contract["target"],
                 "unit": case.get("unit") or contract["unit"],
                 "frequency": case["frequency"], "horizon": horizon,
                 "history_start": case.get("history_start"),
                 "news_quality": case.get("news_quality", "valid"),
                 "require_strict_history_start": True,
                 "required_facts_schema_version": FACTS_SCHEMA_VERSION,
                 "summary_prompt_version": hic.SUMMARY_PROMPT_VERSION}
        query.update(_test6_query_memory_policy(
            contract, dataset=case["dataset"], horizon=horizon,
            prior_online_case_ids=prior_online_case_ids,
        ))
        eligible = _rank_eligible_candidates(candidates, query)
        transfer_eligible = []
        for memory in eligible["eligible"]:
            source_horizon = memory["metadata"].get("horizon")
            source_metadata = memory["metadata"]
            outcome_blind_online_memory = (
                source_metadata.get("split") == "validation"
                and isinstance(query.get("test6_online_round_id"), str)
                and source_metadata.get("test6_round_id")
                == query.get("test6_online_round_id")
                and source_metadata.get("test6_scoring_status") == "complete"
            )
            projection = build_test6_transfer_projection(
                memory.get("correction"), source_horizon=source_horizon,
                test6_transfer_revision=memory["metadata"].get(
                    "test6_transfer_revision"
                ),
                outcome_blind=outcome_blind_online_memory,
                summary=memory.get("summary"),
            )
            if projection is None:
                eligible["excluded_counts"]["no_safe_qualitative_transfer_projection"] = (
                    eligible["excluded_counts"].get(
                        "no_safe_qualitative_transfer_projection", 0
                    ) + 1
                )
                continue
            scope_ok, scope_reason = test6_transfer_scope_eligibility(
                projection, source_metadata=source_metadata, query=query,
            )
            if not scope_ok:
                eligible["excluded_counts"][scope_reason] = (
                    eligible["excluded_counts"].get(scope_reason, 0) + 1
                )
                continue
            memory["test6_transfer_projection"] = projection
            memory["test6_transfer_projection_sha256"] = hashlib.sha256(
                projection.encode("utf-8")
            ).hexdigest()
            transfer_eligible.append(memory)
        allow_different_history_lengths = query.get(
            "horizon_migration_protocol"
        ) in {
            "agent_test6_cross_horizon_v1",
            TEST6_SEMANTIC_TRANSFER_PROTOCOL,
        }
        ranked = rerank_by_text_curve_and_behavior(
            transfer_eligible, case["series"], state["baseline"]["prediction"],
            text_top_k=PARAMETERS["text_top_k"],
            allow_different_history_lengths=allow_different_history_lengths,
        )
        selected = [{key: memory[key] for key in (
            "case_id", "score", "text_similarity",
            "curve_similarity", "behavior_similarity", "combined_score",
            "selection_reason")} | {
                "point_id": memory["point_id"],
                "correction": memory["test6_transfer_projection"],
                "projection_sha256": memory["test6_transfer_projection_sha256"],
                "source_correction_sha256": hashlib.sha256(
                    memory["correction"].encode("utf-8")
                ).hexdigest(),
                "source_horizon": memory["metadata"].get("horizon"),
                "query_horizon": horizon,
                "test6_transfer_revision_id": memory["metadata"].get(
                    "test6_transfer_revision_id"
                ),
                "test6_transfer_revision_sha256": memory["metadata"].get(
                    "test6_transfer_revision_sha256"
                ),
                "summary": memory.get("summary"),
                "source_context": {
                    key: memory["metadata"].get(key)
                    for key in ("dataset", "target", "unit", "frequency", "target_end")
                },
                "source_provenance": {
                    key: memory["metadata"].get(key)
                    for key in ("source_sha256", "split", "test6_round_id",
                                "test6_scoring_status")
                },
            } for memory in ranked[:PARAMETERS["memory_count"]]]
        state["retrieval_trace"] = {"candidate_count": count,
                                     "eligible_count": len(eligible["eligible"]),
                                     "transfer_eligible_count": len(transfer_eligible),
                                     "transfer_projection_version": TEST6_TRANSFER_PROJECTION_VERSION,
                                     "excluded_counts": eligible["excluded_counts"],
                                     "horizon_migration_protocol": query.get("horizon_migration_protocol"),
                                     "query_horizon": horizon,
                                     "allowed_source_horizons": query.get(
                                         "allowed_source_horizons",
                                         "any_valid_recorded_horizon"
                                         if allow_different_history_lengths else [horizon],
                                     ),
                                     "prior_online_case_ids": query.get(
                                         "test6_prior_memory_case_ids"
                                     ),
                                     "text_top_k": PARAMETERS["text_top_k"],
                                     "ranked_candidates": [
                                         {key: memory[key] for key in (
                                             "case_id", "score", "text_similarity",
                                             "curve_similarity", "behavior_similarity",
                                             "combined_score", "selection_reason")} | {
                                                 "point_id": memory["point_id"],
                                                 "projection_sha256": memory["test6_transfer_projection_sha256"],
                                                 "source_correction_sha256": hashlib.sha256(
                                                     memory["correction"].encode("utf-8")
                                                 ).hexdigest(),
                                                 "source_horizon": memory["metadata"].get("horizon"),
                                                 "query_horizon": horizon,
                                                 "test6_transfer_revision_id": memory["metadata"].get(
                                                     "test6_transfer_revision_id"
                                                 ),
                                                 "test6_transfer_revision_sha256": memory["metadata"].get(
                                                     "test6_transfer_revision_sha256"
                                                 ),
                                                 "source_provenance": {
                                                     key: memory["metadata"].get(key)
                                                     for key in ("source_sha256", "split",
                                                                 "test6_round_id",
                                                                 "test6_scoring_status")
                                                 },
                                             }
                                         for memory in ranked
                                     ],
                                     "selected": selected}
        persist()

    selected = state["retrieval_trace"]["selected"]
    if "full_hic" not in state:
        if selected:
            prompt = build_paired_direct_forecast_prompt(
                **paired_input, retrieved_memory=selected[0]
            )
            invoke("full_hic_forecast_paired_v2", prompt,
                   lambda response: _validated_forecast(response, horizon),
                   "full_hic",
                   lambda response: _validated_forecast(response, horizon))
        else:
            state["full_hic"] = {
                "prediction": list(state["baseline"]["prediction"]),
                "reasoning": "No strictly prior eligible memory; paired fallback equals No Retrieval.",
                "fallback_reason": "no_eligible_memory",
            }
            persist()
    state["status"] = "forecast_complete"
    state.pop("pending_task_id", None)
    persist()
    return state


def advance_test6_postscore_memory(case, state, truth, *, contract, cache, persist):
    """Create one numeric-fact-preserving correction after this case is scored."""
    if state.get("status") != "scored" or state.get("forecast_lock_sha256") is None:
        raise ValueError("Test 6 memory reflection requires locked and scored A/B forecasts")
    if not isinstance(truth, list) or len(truth) != contract["horizon"]:
        raise ValueError("validation truth must match the forecast horizon")
    prediction = state["full_hic"]["prediction"]
    facts = compute_error_facts(case["series"], prediction, truth)
    prompt = build_verified_correction_prompt_v4(
        state["summary"], case["series"], truth, prediction,
        state["full_hic"].get("reasoning", ""), facts,
        task_context={
            "dataset": contract["dataset"], "target": contract["target"],
            "unit": contract["unit"], "frequency": contract["frequency"],
            "horizon": contract["horizon"],
        },
    )

    def validate(response):
        make_verified_correction_record_v4(facts, response)
        return True

    cached, _task_id = _invoke_prompt_identity(
        cache,
        f"{cache.run_id}:{case['case_id']}:H{contract['horizon']}:test6_postscore_reflection_v4",
        prompt, call_json=_no_provider_call, validator=validate,
    )
    record = make_verified_correction_record_v4(facts, cached["response"])
    state["online_memory"] = {
        "correction": render_verified_correction_v4(record),
        "facts_sha256": canonical_hash(facts),
        "correction_sha256": canonical_hash(record),
        "reflection_request_sha256": cached["request_identity"]["sha256"],
        "reflection_prompt_version": CORRECTION_PROMPT_VERSION_V4,
        "source_horizon": contract["horizon"],
        "query_horizon": contract["horizon"],
        "basis_prediction": "full_hic",
    }
    persist()
    cache.mark_persisted(cached["request_identity"]["sha256"])
    return state["online_memory"]


def advance_pending_cases(jobs, states, advance, *, max_pending=6, admission_limit=None):
    """Fill at most six independent case slots; retain failures as failures."""
    if type(max_pending) is not int or not 1 <= max_pending <= 6:
        raise ValueError("max_pending must be between one and six")
    if admission_limit is None:
        admission_limit = len(jobs)
    if type(admission_limit) is not int or not 1 <= admission_limit <= len(jobs):
        raise ValueError("admission_limit must be between one and the complete job count")
    admitted = jobs[:admission_limit]
    pending = []
    for job in admitted:
        state = states[job["job_id"]]
        if state.get("status") in {"forecast_complete", "technical_failed"}:
            continue
        try:
            advance(job, state)
        except CodexTaskPending as error:
            state["status"] = "awaiting_agent"
            state["pending_task_id"] = error.task_id
            pending.append({"job_id": job["job_id"], "task_id": error.task_id})
            if len(pending) == max_pending:
                break
    completed = sum(states[row["job_id"]].get("status") == "forecast_complete" for row in admitted)
    failed = sum(states[row["job_id"]].get("status") == "technical_failed" for row in admitted)
    return {"admitted": admission_limit, "total": len(jobs), "completed": completed,
            "failed": failed, "pending": pending}
